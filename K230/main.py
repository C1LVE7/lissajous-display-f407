def _is_trace(pixel):
    if not isinstance(pixel, tuple) or len(pixel) < 3:
        return False
    red, green, blue = pixel[0], pixel[1], pixel[2]
    cyan = (
        red <= TRACE_RED_MAX
        and green >= TRACE_GREEN_MIN
        and blue >= TRACE_BLUE_MIN
        and min(green, blue) - red >= TRACE_COLOR_MARGIN_MIN
        and abs(green - blue) <= TRACE_GB_DELTA_MAX
    )
    return cyan


def _binary_white(pixel):
    if isinstance(pixel, tuple):
        return pixel[0] + pixel[1] + pixel[2] > 300
    return pixel != 0


def _threshold(channel, low, high):
    return channel.binary(
        [(int(low), int(high))], to_bitmap=True, copy=True)


def _histogram_trimmed_bounds(histogram, trim_fraction):
    total = sum(histogram)
    if total <= 0:
        return None
    trim_count = int(total * trim_fraction)
    accumulated = 0
    low = 0
    for index, value in enumerate(histogram):
        accumulated += value
        if accumulated > trim_count:
            low = index
            break
    accumulated = 0
    high = len(histogram) - 1
    for index in range(len(histogram) - 1, -1, -1):
        accumulated += histogram[index]
        if accumulated > trim_count:
            high = index
            break
    if high <= low:
        return None
    return low, high


def _extract_clusters(histogram, merge_gap, min_pixels, min_span):
    """Exact one-dimensional weighted clustering from 老哥/测频.txt."""
    active = [index for index, value in enumerate(histogram) if value > 0]
    if not active:
        return []
    groups = []
    start = active[0]
    previous = active[0]
    for current in active[1:]:
        if current - previous <= merge_gap:
            previous = current
        else:
            groups.append((start, previous))
            start = current
            previous = current
    groups.append((start, previous))

    clusters = []
    for start, end in groups:
        pixel_sum = 0
        weighted_sum = 0
        for index in range(start, end + 1):
            value = histogram[index]
            pixel_sum += value
            weighted_sum += index * value
        if pixel_sum < min_pixels or end - start + 1 < min_span:
            continue
        center = float(weighted_sum) / float(pixel_sum)
        clusters.append((center, start, end, pixel_sum))
    return clusters


