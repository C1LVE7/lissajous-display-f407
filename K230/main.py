    def _native_trace_mask(self, image):
        """Build the six-condition cyan gate with native image operations."""
        roi = SCREEN_ROI
        red = image.to_grayscale(roi=roi, rgb_channel=0)
        green = image.to_grayscale(roi=roi, rgb_channel=1)
        blue = image.to_grayscale(roi=roi, rgb_channel=2)

        mask = _threshold(red, 0, TRACE_RED_MAX)
        gate = _threshold(green, TRACE_GREEN_MIN, 255)
        mask.b_and(gate)
        gate = _threshold(blue, TRACE_BLUE_MIN, 255)
        mask.b_and(gate)

        green_minus_red = green.copy()
        green_minus_red.sub(red)
        gate = _threshold(
            green_minus_red, TRACE_COLOR_MARGIN_MIN, 255)
        mask.b_and(gate)

        blue_minus_red = blue.copy()
        blue_minus_red.sub(red)
        gate = _threshold(
            blue_minus_red, TRACE_COLOR_MARGIN_MIN, 255)
        mask.b_and(gate)

        green_minus_blue = green.copy()
        green_minus_blue.sub(blue)
        gate = _threshold(green_minus_blue, 0, TRACE_GB_DELTA_MAX)
        mask.b_and(gate)

        blue_minus_green = blue.copy()
        blue_minus_green.sub(green)
        gate = _threshold(blue_minus_green, 0, TRACE_GB_DELTA_MAX)
        mask.b_and(gate)

        left, top, width, height = roi
        margin = TRACE_BORDER_MARGIN
        mask.draw_rectangle((0, 0, width, margin), color=0, fill=True)
        mask.draw_rectangle(
            (0, height - margin, width, margin), color=0, fill=True)
        mask.draw_rectangle((0, 0, margin, height), color=0, fill=True)
        mask.draw_rectangle(
            (width - margin, 0, margin, height), color=0, fill=True)
        for ex_left, ex_top, ex_width, ex_height in TRACE_EXCLUDE_RECTS:
            mask.draw_rectangle(
                (ex_left - left, ex_top - top, ex_width, ex_height),
                color=0, fill=True)
        red = None
        green = None
        blue = None
        gate = None
        green_minus_red = None
        blue_minus_red = None
        green_minus_blue = None
        blue_minus_green = None
        return mask

    @staticmethod
    def _mask_points(mask, step, bounds=None):
        left, top, width, height = SCREEN_ROI
        margin = TRACE_BORDER_MARGIN
        if bounds is None:
            x0 = margin
            y0 = margin
            x1 = width - margin - 1
            y1 = height - margin - 1
        else:
            x0, y0, box_width, box_height = bounds
            x0 = max(margin, x0)
            y0 = max(margin, y0)
            x1 = min(width - margin - 1, x0 + box_width - 1)
            y1 = min(height - margin - 1, y0 + box_height - 1)
        points = []
        for local_y in range(y0, y1 + 1, int(step)):
            for local_x in range(x0, x1 + 1, int(step)):
                if _binary_white(mask.get_pixel(local_x, local_y)):
                    points.append((left + local_x, top + local_y))
        return points

