import math


def trimmed_bounds(values, fraction=0.02):
    if not values:
        return None
    ordered = sorted(values)
    trim = int(len(ordered) * fraction)
    if trim * 2 >= len(ordered) - 2:
        trim = 0
    return ordered[trim], ordered[len(ordered) - 1 - trim]


def _fit_axes_once(points):
    if len(points) < 12:
        return None
    count = len(points)
    center_x = sum(point[0] for point in points) / count
    center_y = sum(point[1] for point in points) / count
    cov_xx = sum((x - center_x) ** 2 for x, _ in points) / count
    cov_yy = sum((y - center_y) ** 2 for _, y in points) / count
    cov_xy = sum((x - center_x) * (y - center_y) for x, y in points) / count
    if cov_xx + cov_yy < 1e-9:
        return None
    theta = 0.5 * math.atan2(2.0 * cov_xy, cov_xx - cov_yy)
    ux = math.cos(theta)
    uy = math.sin(theta)
    vx = -uy
    vy = ux
    var_u = ux * ux * cov_xx + 2.0 * ux * uy * cov_xy + uy * uy * cov_yy
    var_v = vx * vx * cov_xx + 2.0 * vx * vy * cov_xy + vy * vy * cov_yy
    if var_v > var_u:
        ux, uy = vx, vy
    if ux < 0.0:
        ux, uy = -ux, -uy
    vx, vy = -uy, ux
    major_values = []
    minor_values = []
    for x, y in points:
        dx = x - center_x
        dy = y - center_y
        major_values.append(dx * ux + dy * uy)
        minor_values.append(dx * vx + dy * vy)
    major_bounds = trimmed_bounds(major_values)
    minor_bounds = trimmed_bounds(minor_values)
    if major_bounds is None or minor_bounds is None:
        return None
    major_length = major_bounds[1] - major_bounds[0]
    minor_length = minor_bounds[1] - minor_bounds[0]
    if minor_length > major_length:
        ux, uy = vx, vy
        if ux < 0.0:
            ux, uy = -ux, -uy
        vx, vy = -uy, ux
        major_values = []
        minor_values = []
        for x, y in points:
            dx = x - center_x
            dy = y - center_y
            major_values.append(dx * ux + dy * uy)
            minor_values.append(dx * vx + dy * vy)
        major_bounds = trimmed_bounds(major_values)
        minor_bounds = trimmed_bounds(minor_values)
        major_length = major_bounds[1] - major_bounds[0]
        minor_length = minor_bounds[1] - minor_bounds[0]
    if major_length <= 1e-6 or minor_length < 0.0:
        return None
    major_mid = 0.5 * (major_bounds[0] + major_bounds[1])
    minor_mid = 0.5 * (minor_bounds[0] + minor_bounds[1])
    center_x += major_mid * ux + minor_mid * vx
    center_y += major_mid * uy + minor_mid * vy
    return center_x, center_y, ux, uy, major_length, minor_length


def principal_fit(points):
    """Two-pass PCA/ellipse filtering from 老哥的代码/主程序.py."""
    first = _fit_axes_once(points)
    if first is None:
        return None
    center_x, center_y, ux, uy, major_length, minor_length = first
    major_radius = major_length * 0.5
    minor_radius = minor_length * 0.5
    if major_radius <= 1e-6 or minor_radius <= 1e-6:
        return first
    vx = -uy
    vy = ux
    refined = []
    for x, y in points:
        dx = x - center_x
        dy = y - center_y
        major_value = (dx * ux + dy * uy) / major_radius
        minor_value = (dx * vx + dy * vy) / minor_radius
        rho = major_value * major_value + minor_value * minor_value
        if 0.45 <= rho <= 1.65:
            refined.append((x, y))
    minimum_refined = max(60, int(len(points) * 0.35))
    if len(refined) >= minimum_refined:
        second = _fit_axes_once(refined)
        if second is not None:
            return second
    return first


def _mirror_error(cells, width, height, horizontal):
    if not cells:
        return 1.0
    misses = 0
    for x, y in cells:
        target_x = width - 1 - x if horizontal else x
        target_y = y if horizontal else height - 1 - y
        found = False
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                if (target_x + dx, target_y + dy) in cells:
                    found = True
                    break
            if found:
                break
        if not found:
            misses += 1
    return misses / float(len(cells))


def _crossing_cluster_count(values, gap=0.28):
    if not values:
        return 0
    ordered = sorted(values)
    count = 1
    previous = ordered[0]
    for value in ordered[1:]:
        if value - previous > gap:
            count += 1
        previous = value
    return count


def analyze_shape(points, px_per_div_x, px_per_div_y):
    if len(points) < 20:
        return {"ok": False, "point_count": len(points)}
    normalized = [(x / px_per_div_x, -y / px_per_div_y) for x, y in points]
    fit = principal_fit(normalized)
    if fit is None:
        return {"ok": False, "point_count": len(points)}
    center_x, center_y, ux, uy, major_length, minor_length = fit
    ratio = max(0.0, min(1.0, minor_length / max(major_length, 1e-9)))
    # Component filtering already removed UI fragments. Keep only a 0.5%
    # trim here; 2% shortens a thin diagonal by about 0.3 div and can reject a
    # physically correct 8 div line at the required 0.2 div amplitude gate.
    x_bounds = trimmed_bounds([p[0] for p in normalized], 0.005)
    y_bounds = trimmed_bounds([p[1] for p in normalized], 0.005)
    width_div = x_bounds[1] - x_bounds[0]
    height_div = y_bounds[1] - y_bounds[0]
    folded = 2.0 * math.atan(ratio) * 180.0 / math.pi
    phase = folded if uy >= 0.0 else 180.0 - folded
    if ratio >= 0.93:
        phase = 90.0

    ellipse_error = ratio
    if minor_length > 0.10:
        vx = -uy
        vy = ux
        major_radius = max(major_length * 0.5, 1e-6)
        minor_radius = max(minor_length * 0.5, 1e-6)
        residuals = []
        for x, y in normalized:
            dx = x - center_x
            dy = y - center_y
            major_value = (dx * ux + dy * uy) / major_radius
            minor_value = (dx * vx + dy * vy) / minor_radius
            radius = math.sqrt(
                major_value * major_value + minor_value * minor_value)
            residuals.append(abs(radius - 1.0))
        residuals.sort()
        ellipse_error = residuals[len(residuals) // 2]

    crossing_half_width = 0.06
    vertical_crossings = _crossing_cluster_count([
        y for x, y in normalized
        if abs(x - center_x) <= crossing_half_width
    ])
    horizontal_crossings = _crossing_cluster_count([
        x for x, y in normalized
        if abs(y - center_y) <= crossing_half_width
    ])

    grid_w = 32
    grid_h = 24
    cells = set()
    center_hits = 0
    for x, y in normalized:
        nx = (x - x_bounds[0]) / max(width_div, 1e-9)
        ny = (y - y_bounds[0]) / max(height_div, 1e-9)
        gx = max(0, min(grid_w - 1, int(nx * (grid_w - 1) + 0.5)))
        gy = max(0, min(grid_h - 1, int(ny * (grid_h - 1) + 0.5)))
        cells.add((gx, gy))
        if abs(nx - 0.5) <= 0.08 and abs(ny - 0.5) <= 0.10:
            center_hits += 1
    symmetry_x = _mirror_error(cells, grid_w, grid_h, True)
    symmetry_y = _mirror_error(cells, grid_w, grid_h, False)
    center_fraction = center_hits / float(len(normalized))
    return {
        "ok": True,
        "point_count": len(points),
        "axis_ratio": ratio,
        "ellipse_error": ellipse_error,
        "vertical_crossings": vertical_crossings,
        "horizontal_crossings": horizontal_crossings,
        "phase_deg": phase,
        "major_div": major_length,
        "minor_div": minor_length,
        "width_div": width_div,
        "height_div": height_div,
        "symmetry_x": symmetry_x,
        "symmetry_y": symmetry_y,
        "center_fraction": center_fraction,
    }


def shape_score(metrics, shape, target_span=8.0):
    if not metrics.get("ok"):
        return 1e9
    span_error = (abs(metrics["width_div"] - target_span)
                  + abs(metrics["height_div"] - target_span))
    ratio = metrics["axis_ratio"]
    if shape == "LINE":
        return 6.0 * ratio + 0.12 * span_error
    if shape == "CIRCLE":
        return 6.0 * abs(1.0 - ratio) + 0.12 * span_error
    center_penalty = max(0.0, 0.03 - metrics["center_fraction"]) * 20.0
    return (2.5 * (metrics["symmetry_x"] + metrics["symmetry_y"])
            + center_penalty + 0.10 * span_error)


def frequency_score(metrics, multiplier, target_span=8.0):
    """Phase-independent score for locating the 1:1 or 1:2 ratio."""
    if not metrics.get("ok"):
        return 1e9
    span_error = (abs(metrics["width_div"] - target_span)
                  + abs(metrics["height_div"] - target_span))
    if int(multiplier) == 1:
        # Every same-frequency Lissajous trace is a single ellipse (with a
        # line as its degenerate case), independent of relative phase.
        topology_error = min(
            metrics.get("ellipse_error", 1.0),
            metrics.get("axis_ratio", 1.0),
        )
        return 8.0 * topology_error + 0.10 * span_error
    horizontal_crossings = metrics.get("horizontal_crossings", 0)
    horizontal_error = max(
        0, 2 - horizontal_crossings, horizontal_crossings - 4)
    crossing_error = (
        2.0 * abs(metrics.get("vertical_crossings", 0) - 1)
        + horizontal_error
    )
    return (crossing_error
            + 0.5 * shape_score(metrics, "INFINITY", target_span))


def shape_locked(metrics, shape, config):
    if not metrics.get("ok"):
        return False
    span_ok = (abs(metrics["width_div"] - TARGET_SPAN_DIV)
               <= SPAN_TOLERANCE_DIV
               and abs(metrics["height_div"] - TARGET_SPAN_DIV)
               <= SPAN_TOLERANCE_DIV)
    if getattr(config, "REQUIRE_SPAN_FOR_LOCK", True) and not span_ok:
        return False
    # Reject small grid/UI fragments, but keep the gate deliberately broad:
    # requirement 5 uses a fixed analog gain and only needs a visually similar
    # full-size target for the single-frame decision.
    fuzzy_span_ok = (
        metrics["width_div"] >= FUZZY_MIN_SPAN_DIV
        and metrics["height_div"] >= FUZZY_MIN_SPAN_DIV
    )
    if shape == "LINE":
        return (fuzzy_span_ok
                and metrics["axis_ratio"] <= LINE_AXIS_RATIO_MAX)
    if shape == "CIRCLE":
        return (fuzzy_span_ok
                and metrics["axis_ratio"] >= CIRCLE_AXIS_RATIO_MIN
                and metrics.get("phase_deg", 0.0)
                >= CIRCLE_PHASE_MIN_DEG
                and metrics.get("ellipse_error", 1.0)
                <= CIRCLE_ELLIPSE_ERROR_MAX
                and metrics.get("center_fraction", 1.0)
                <= CIRCLE_CENTER_FRACTION_MAX)
    geometry_ok = (
        metrics.get("axis_ratio", 0.0) >= INFINITY_AXIS_RATIO_MIN
        and metrics["symmetry_x"] + metrics["symmetry_y"]
        <= INFINITY_SYMMETRY_MAX
        and INFINITY_CENTER_MIN
        <= metrics["center_fraction"] <= INFINITY_CENTER_MAX
        and INFINITY_HORIZONTAL_CROSSINGS_MIN
        <= metrics.get("horizontal_crossings", 0)
        <= INFINITY_HORIZONTAL_CROSSINGS_MAX
    )
    if not geometry_ok:
        return False
    return fuzzy_span_ok and geometry_ok


def shape_perfect(metrics, shape):
    """Single-frame quality gate used to stop frequency changes."""
    if not metrics.get("ok"):
        return False
    if (metrics["width_div"] < FUZZY_MIN_SPAN_DIV
            or metrics["height_div"] < FUZZY_MIN_SPAN_DIV):
        return False
    shape = str(shape).upper()
    if shape == "LINE":
        return metrics["axis_ratio"] <= PERFECT_LINE_AXIS_RATIO_MAX
    if shape == "CIRCLE":
        return (metrics["axis_ratio"] >= PERFECT_CIRCLE_AXIS_RATIO_MIN
                and metrics.get("phase_deg", 0.0)
                >= CIRCLE_PHASE_MIN_DEG
                and metrics.get("ellipse_error", 1.0)
                <= CIRCLE_ELLIPSE_ERROR_MAX
                and metrics.get("center_fraction", 1.0)
                <= CIRCLE_CENTER_FRACTION_MAX)
    return (metrics.get("axis_ratio", 0.0) >= INFINITY_AXIS_RATIO_MIN
            and metrics.get("symmetry_x", 1.0)
            + metrics.get("symmetry_y", 1.0)
            <= PERFECT_INFINITY_SYMMETRY_MAX
            and INFINITY_CENTER_MIN
            <= metrics.get("center_fraction", 0.0)
            <= INFINITY_CENTER_MAX
            and INFINITY_HORIZONTAL_CROSSINGS_MIN
            <= metrics.get("horizontal_crossings", 0)
            <= INFINITY_HORIZONTAL_CROSSINGS_MAX)


def shape_final(metrics, shape):
    """Strict gate for announcing LOCKED after frequency acquisition."""
    if not shape_perfect(metrics, shape):
        return False
    if str(shape).upper() == "LINE":
        return metrics["axis_ratio"] <= FINAL_LINE_AXIS_RATIO_MAX
    if str(shape).upper() == "INFINITY":
        return (metrics["axis_ratio"] <= FINAL_INFINITY_AXIS_RATIO_MAX
                and INFINITY_CENTER_MIN
                <= metrics.get("center_fraction", 0.0)
                <= INFINITY_CENTER_MAX)
    return True


def unwrap_phase_slope(phases, elapsed_ms, period=180.0):
    if len(phases) < 3 or len(phases) != len(elapsed_ms):
        return None
    unwrapped = [float(phases[0])]
    for value in phases[1:]:
        candidate = float(value)
        previous = unwrapped[-1]
        while candidate - previous > period * 0.5:
            candidate -= period
        while candidate - previous < -period * 0.5:
            candidate += period
        unwrapped.append(candidate)
    mean_t = sum(elapsed_ms) / float(len(elapsed_ms))
    mean_p = sum(unwrapped) / float(len(unwrapped))
    numerator = 0.0
    denominator = 0.0
    for t_ms, phase in zip(elapsed_ms, unwrapped):
        dt = float(t_ms) - mean_t
        numerator += dt * (phase - mean_p)
        denominator += dt * dt
    if denominator <= 1e-9:
        return None
    return numerator / denominator * 1000.0

