class SweepHoldController:
    def __init__(self, camera, link):
        self.camera = camera
        self.link = link
        self.seq = 0
        self.capture_count = 0
        self.probe_id = 0
        self.nominal_frequency_millihz = 0
        self.commanded_frequency_millihz = 0
        self.frequency_trim_millihz = 0
        self.phase_millideg = 0
